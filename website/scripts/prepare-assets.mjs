import './build-social.mjs';
import './prepare-web-art.mjs';
import { createHash } from 'node:crypto';
import { copyFile, mkdir, readdir, readFile, writeFile } from 'node:fs/promises';

const root = new URL('../', import.meta.url);
const copy = (from, to) => copyFile(new URL(from, root), new URL(to, root));
async function copyReview(from, to) {
  const html = await readFile(new URL(from, root), 'utf8');
  await writeFile(new URL(to, root), html.replace(/<title/i, '<meta name="robots" content="noindex,follow"><title'));
}
await mkdir(new URL('public/kit/', root), { recursive: true });
await mkdir(new URL('public/fonts/', root), { recursive: true });
await mkdir(new URL('src/generated/', root), { recursive: true });

await copy('../assets/mascot/nery-mizuki-avatar.webp', 'public/nery-mizuki-avatar.webp');
await copy('../pet/nery/spritesheet.webp', 'public/spritesheet.webp');
await copy('../pet/nery/walk-16.webp', 'public/walk-16.webp');
await copy('../pet/nery/walk-32.webp', 'public/walk-32.webp');
await copy('../pet/preview/walk-16.gif', 'public/walk-16.gif');
await copy('../pet/preview/walk-32.gif', 'public/walk-32.gif');
await copy('../pet/preview/web-failed.gif', 'public/failed.gif');
await copy('../pet/nery/pet.json', 'public/pet.json');
await copy('../pet/nery/motion.webp', 'public/motion.webp');
await copy('../pet/nery/motion.json', 'public/motion.json');
await copy('../pet/occasions/occasions.webp', 'public/occasions.webp');
await copy('../pet/occasions/celebrate.gif', 'public/celebrate.gif');
await copy('../pet/occasions/heart.gif', 'public/heart.gif');
await copyReview('../pet/occasions/review.html', 'public/occasions-review.html');
const occasionsData = await readFile(new URL('../pet/occasions/occasions.json', root), 'utf8');
await writeFile(new URL('src/generated/occasions-data.ts', root),
  '// Generated by prepare-assets.mjs; do not edit manually.\n' +
  `export const occasions = ${occasionsData.trim()} as const;\n`);
await mkdir(new URL('public/kit-v2/', root), { recursive: true });
for (const name of await readdir(new URL('../assets/mascot/kit-v2/transparent/', root))) {
  if (name.endsWith('.webp')) await copy(`../assets/mascot/kit-v2/transparent/${name}`, `public/kit-v2/${name}`);
}
const occasionPoses = await readFile(new URL('../assets/mascot/kit-v2/manifest.json', root), 'utf8');
await writeFile(new URL('src/generated/occasion-poses.ts', root),
  '// Generated by prepare-assets.mjs; do not edit manually.\n' +
  `export const occasionKit = ${occasionPoses.trim()} as const;\n`);
await copyReview('../pet/preview/motion-review.html', 'public/motion-review.html');
await copyReview('../pet/preview/walk-review.html', 'public/walk-review.html');
await copyReview('../pet/candidates/walk-proportions/comparison.html', 'public/walk-candidate-review.html');

// Vite serves files in /public as-is. Hash the sprite CONTENT and
// include it in the URL so a stale cached atlas can never flash old frames.
// Retain the canonical /spritesheet.webp path for Petdex users.
const spriteBytes = await readFile(new URL('../pet/nery/spritesheet.webp', root));
const spriteVersion = createHash('sha256').update(spriteBytes).digest('hex').slice(0, 16);
const walkBytes = await readFile(new URL('../pet/nery/walk-16.webp', root));
const walkVersion = createHash('sha256').update(walkBytes).digest('hex').slice(0, 16);
const motionBytes = await readFile(new URL('../pet/nery/motion.webp', root));
const motionData = await readFile(new URL('../pet/nery/motion.json', root), 'utf8');
const motionVersion = createHash('sha256').update(motionBytes).update(motionData).digest('hex').slice(0, 16);
await writeFile(new URL('src/generated/pet-asset-version.ts', root),
  '// Generated by website/scripts/prepare-assets.mjs; do not edit manually.\n' +
  `export const petAssetVersion = '${spriteVersion}' as const;\n` +
  `export const walkAssetVersion = '${walkVersion}' as const;\n` +
  `export const motionAssetVersion = '${motionVersion}' as const;\n`);
await writeFile(new URL('src/generated/motion-data.ts', root),
  '// Generated from pet/nery/motion.json; do not edit manually.\n' +
  `export const motion = ${motionData.trim()} as const;\n`);

for (const name of await readdir(new URL('../assets/mascot/kit-v1/transparent/', root))) {
  if (name.endsWith('.webp')) {
    await copy(`../assets/mascot/kit-v1/transparent/${name}`, `public/kit/${name}`);
  }
}
await copy('node_modules/@fontsource-variable/geist/files/geist-latin-wght-normal.woff2',
  'public/fonts/geist-latin-wght-normal.woff2');
