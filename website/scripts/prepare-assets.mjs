import { createHash } from 'node:crypto';
import { copyFile, mkdir, readdir, readFile, writeFile } from 'node:fs/promises';

const root = new URL('../', import.meta.url);
const copy = (from, to) => copyFile(new URL(from, root), new URL(to, root));
await mkdir(new URL('public/kit/', root), { recursive: true });
await mkdir(new URL('public/fonts/', root), { recursive: true });
await mkdir(new URL('src/generated/', root), { recursive: true });

await copy('../assets/mascot/nery-mizuki-avatar.webp', 'public/nery-mizuki-avatar.webp');
await copy('../pet/nery/spritesheet.webp', 'public/spritesheet.webp');
await copy('../pet/nery/walk-16.webp', 'public/walk-16.webp');
await copy('../pet/preview/walk-16.gif', 'public/walk-16.gif');
await copy('../pet/nery/pet.json', 'public/pet.json');

// Astro/Vite serves files in /public as-is. Hash the sprite CONTENT and
// include it in the URL so a stale cached atlas can never flash old frames.
// Retain the canonical /spritesheet.webp path for Petdex users.
const spriteBytes = await readFile(new URL('../pet/nery/spritesheet.webp', root));
const spriteVersion = createHash('sha256').update(spriteBytes).digest('hex').slice(0, 16);
const walkBytes = await readFile(new URL('../pet/nery/walk-16.webp', root));
const walkVersion = createHash('sha256').update(walkBytes).digest('hex').slice(0, 16);
await writeFile(new URL('src/generated/pet-asset-version.ts', root),
  '// Generated by website/scripts/prepare-assets.mjs; do not edit manually.\n' +
  `export const petAssetVersion = '${spriteVersion}' as const;\n` +
  `export const walkAssetVersion = '${walkVersion}' as const;\n`);

for (const name of await readdir(new URL('../assets/mascot/kit-v1/transparent/', root))) {
  if (name.endsWith('.webp')) {
    await copy(`../assets/mascot/kit-v1/transparent/${name}`, `public/kit/${name}`);
  }
}
await copy('node_modules/@fontsource-variable/geist/files/geist-latin-wght-normal.woff2',
  'public/fonts/geist-latin-wght-normal.woff2');
