import { createHash } from 'node:crypto';
import { mkdir, readdir, readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import sharp from 'sharp';

const root = new URL('../', import.meta.url);
const sources = new URL('../assets/mascot/', root);
const output = new URL('public/generated-art/', root);
await mkdir(output, { recursive: true });
await mkdir(new URL('src/generated/', root), { recursive: true });

async function publish(data, filename) {
  const version = createHash('sha256').update(data).digest('hex').slice(0, 16);
  await writeFile(new URL(filename, output), data);
  return `/generated-art/${filename}?v=${version}`;
}

async function render(image, filename) {
  const { data, info } = await image.toBuffer({ resolveWithObject: true });
  return { src: await publish(data, filename), width: info.width, height: info.height };
}

const portrait = new URL('kit-v1/transparent/nery-portrait.png', sources);
const hero = {};
for (const [format, options] of [['avif', { quality: 55 }], ['webp', { quality: 85 }], ['png', {}]]) {
  const variants = await Promise.all([320, 480, 640, 745].map(width => render(
    sharp(fileURLToPath(portrait)).resize({ width }).toFormat(format, options),
    `portrait-${width}.${format}`,
  )));
  hero[format] = variants.map(({ src, width }) => `${src} ${width}w`).join(', ');
  if (format === 'png') hero.fallback = variants.at(-1).src;
}

const gallery = {};
for (const kit of ['kit-v1', 'kit-v2']) {
  const originals = new URL(`${kit}/transparent/`, sources);
  const filenames = (await readdir(originals)).filter(name => /^nery-.+\.png$/.test(name)).sort();
  for (const name of filenames) {
    const id = name.slice(5, -4);
    gallery[id] = await render(
      sharp(fileURLToPath(new URL(name, originals))).resize({ width: 380, withoutEnlargement: true }).webp({ quality: 85 }),
      `gallery-${id}.webp`,
    );
  }
}

const atlases = {};
for (const [key, source] of [['motion', '../pet/nery/motion.webp'], ['occasions', '../pet/occasions/occasions.webp']]) {
  const { src } = await render(
    sharp(fileURLToPath(new URL(source, root))).webp({ quality: 95 }),
    `${key}.webp`,
  );
  atlases[key] = src;
}

const microIcons = await Promise.all([16, 24, 32, 48].map(async size => {
  const bytes = await readFile(new URL(`../assets/icons/micro/png/nery-${size}.png`, root));
  return { size, src: await publish(bytes, `micro-${size}.png`) };
}));

await writeFile(new URL('src/generated/web-art.ts', root), [
  '// Generated by prepare-web-art.mjs; do not edit manually.',
  `export const heroImages = ${JSON.stringify(hero, null, 2)};`,
  `export const galleryImages: Record<string, { src: string; width: number; height: number }> = ${JSON.stringify(gallery, null, 2)};`,
  `export const animationAtlases = ${JSON.stringify(atlases, null, 2)};`,
  `export const microIcons = ${JSON.stringify(microIcons, null, 2)};`,
  '',
].join('\n'));
